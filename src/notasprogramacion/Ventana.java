    public void registrarBoletin () {
        String nom, ape;
        double tJava, pJava, aJava, tC, pC, aC;
        
        //Validacion de Nombre y Apellidos
        
        if ("".equals(campoNombre.getText().trim()=="")) {
            JOptionPane.showMessageDialog(this, "El campo nombre es obligatorio");
            return;
        }
        
        if ("".equals(campoApellidos.getText().trim()=="")) {
            JOptionPane.showMessageDialog(this, "El campo apellidos es obligatorio");
            return;
        }
        
        //Validacion de notas Java
        
        try {
            tJava = Double.parseDouble(campoTareasJava.getText().trim());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(this, "La nota de tareas java es obligatoria");
            return;
        }
        
        try {
             pJava= Double.parseDouble(campoPoJava.getText().trim());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(this, "La nota de PO java es obligatoria");
            return;
        }
        
        try {
             aJava= Double.parseDouble(campoAptitudesJava.getText().trim());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(this, "La nota de APTITUD java es obligatoria");
            return;
        }
        
        //Validacion de notas C
        
        try {
             tC= Double.parseDouble(campoTareasCsharp.getText().trim());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(this, "La nota de tareas C es obligatoria");
            return;
        }
        
        try {
             pC= Double.parseDouble(campoPoCsharp.getText().trim());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(this, "La nota de PO C es obligatoria");
            return;
        }
        
        try {
             aC= Double.parseDouble(campoAptitudesCsharp.getText().trim());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(this, "La nota de APTITUD C es obligatoria");
            return;
        }
        
        //Asignacion de valores a variables sin valor
        
        nom = campoNombre.getText().trim().toUpperCase();
        ape = campoApellidos.getText().trim().toUpperCase();
        
        //Creacion del objeto de tipo boletin
        
        Boletin b = new Boletin (nom, ape, tJava, pJava, aJava, tC, pC, aC);
        
        campoGlobalJava.setText(String.valueOf(b.notaJava()));
        campoGlobalCsharp.setText(String.valueOf(b.notaCesharp()));
        campoNotaTotalProgramacion.setText(String.valueOf(b.notaGlobal()));
        
        campoFicha.setText(b.toString());
        
        boletines.add(b);
        
        resetear();
        
        
    }

